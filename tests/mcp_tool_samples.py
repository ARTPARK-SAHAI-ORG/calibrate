def write_samples(tools_dir: Path, samples: dict[str, str] | None = None) -> Path:
    """Write the synthetic tool files into ``tools_dir`` and return it."""
    tools_dir = Path(tools_dir)
    tools_dir.mkdir(parents=True, exist_ok=True)
    for name, text in (samples or SAMPLES).items():
        (tools_dir / name).write_text(text, encoding="utf-8")
    return tools_dir


