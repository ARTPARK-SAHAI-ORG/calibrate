"""Synthetic Speakeasy MCP tool files + a matching OpenAPI spec for the tests.

We intentionally do NOT snapshot the real ``calibrate-mcp`` tool files — that
drifts and would pin tests to upstream wording. Instead these hand-built samples
exercise every parsing/rendering variation the generator must handle:

- a read-only tool with a single path parameter;
- a write tool whose body is a ``$ref`` object (required + optional props);
- a write tool whose body is ``anyOf: [Ref, null]`` (an optional request body);
- a read-only tool with no arguments at all;
- a multi-line ``description`` template literal (collapsed to one line in tables);
- a non-tool file (no ``name:``) that must be skipped.

The OpenAPI spec below is self-consistent with the tool files: each tool's
``models/<stem>.js`` import equals ``operation_key(operationId)`` for one of
these operations, so the generator can match them.

The live server is validated separately by the sync workflow.
"""

